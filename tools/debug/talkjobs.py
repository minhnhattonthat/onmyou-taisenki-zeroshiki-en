"""Text coverage for the scripts StartScript has no id for: Kogenta's L-button talk and the tutorial-battle scripts.

    python -X utf8 tools/debug/cover.py report      # first: work/qa/cover/report.txt
    python -X utf8 tools/debug/talkjobs.py [--jobs 8] [--list]

The L-button talk script (pinned 0x6918F4, run by code through the slot word at 0x6918E8) and the five tutorial
scripts (pointer table 0x693080) are not in any StartScript table, so `labeljobs.py` can't jump into them. This
writes build/talk.gba: a copy of the built ROM whose empty id slots 705.. (table 0x41F848, entries hold 0x0200A000)
point at those scripts' slots. Nothing else changes, so build/strings.tsv still maps every text to its address.
Each unseen line then gets a scene: `raw /123 0004 0000 0000 ID LABEL` (jump to the nearest label before it) or
`script ID` when no label precedes it. Out: work/qa/cover/talk/<scene>/log.txt (counted by `cover.py report`).
Coverage only: never ship build/talk.gba.
"""
import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "debug"))
from skill import SKILL  # noqa: E402
import cover  # noqa: E402
import labeljobs  # noqa: E402
import script_index  # noqa: E402

OUT = ROOT / "work" / "qa" / "cover" / "talk"
TALK_ROM = ROOT / "build" / "talk.gba"
ID_TABLE = 0x41F848  # ids 700..999
FIRST_ID = 705  # 705..710 are empty (0x0200A000)
PINNED_SLOT_WORD = 0x6918E8  # u32 -> the talk script's slot
TUTORIAL_TABLE = 0x693080  # 5 u32, each -> a tutorial script (the table words act as slots)


def u32(d, o):
    return struct.unpack_from("<I", d, o)[0]


def extra_slots(d):
    """[(slot address in d, file offset of the script in d)]: the talk script, then the tutorial scripts."""
    slots = [u32(d, PINNED_SLOT_WORD)] + [0x08000000 + TUTORIAL_TABLE + 4 * k for k in range(5)]
    return [(s, u32(d, s & 0x1FFFFFF) & 0x1FFFFFF) for s in slots]


def make_rom():
    built = bytearray(cover.ROM.read_bytes())
    for k, (slot, _) in enumerate(extra_slots(built)):
        e = ID_TABLE + 4 * (FIRST_ID - 700 + k)
        assert u32(built, e) == script_index.EMPTY, f"id {FIRST_ID + k} slot is not empty"
        struct.pack_into("<I", built, e, slot)
    TALK_ROM.write_bytes(built)


def plan():
    miss = labeljobs.unseen()
    orig = script_index.ROM.read_bytes()
    rows = {}
    for k, (_, off) in enumerate(extra_slots(orig)):
        sid, end = FIRST_ID + k, orig.index(b"\0", off)
        labels = [(m.start(), int(m.group(1))) for m in labeljobs.LABEL.finditer(orig, off, end)]
        for t in sorted(t for t in miss if off <= t < end):
            before = [n for pos, n in labels if pos < t]
            if before:
                rows.setdefault(f"talk_{sid}_{before[-1]} raw /123000400000000{sid:04d}{before[-1]:04d} hold=2400",
                                []).append(t)
            else:
                rows.setdefault(f"talk_{sid}_0 script {sid} hold=2400", []).append(t)
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", default="8")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    rows = plan()
    print(f"{len(rows)} scenes for {sum(len(v) for v in rows.values())} lines")
    if a.list:
        for r, ts in rows.items():
            print(r.split()[0], " ".join(f"{t:X}" for t in ts))
        return
    make_rom()
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "scenes.txt"
    path.write_text("# generated by tools/debug/talkjobs.py\n" + "\n".join(rows) + "\n", encoding="utf-8")
    cmd = [sys.executable, "-X", "utf8", str(ROOT / "tools" / "debug" / "warp_all.py"), str(TALK_ROM),
           "--scenes", str(path), "--out", str(OUT), "--states", str(OUT / "states"), "--jobs", a.jobs,
           "--probe", str(Path(SKILL) / "scripts" / "lua" / "probes" / "textcover.lua"),
           "--var", f"RANGES='{cover.ranges()}'"]
    sys.exit(subprocess.run(cmd).returncode)


if __name__ == "__main__":
    main()
