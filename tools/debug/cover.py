"""Text coverage run (phase 8 gate): warp to every event script that holds text, log which text the game reads, report
what was never reached.

    python -X utf8 tools/debug/cover.py scenes            # work/qa/cover/scenes.txt: one `script ID` scene per script
    python -X utf8 tools/debug/cover.py ranges            # the RANGES var for textcover.lua (from build/strings.tsv)
    python -X utf8 tools/debug/cover.py run [--only a,b] [--jobs 4]   # warp_all over those scenes + the probe
    python -X utf8 tools/debug/cover.py report            # textcover.py over every log (work/qa/cover + tours)

Needs build/strings.tsv (written by build.py: id -> address of the text's first byte in the built ROM). Logs go to
work/qa/cover/run/<scene>/log.txt; tours run with `--probe <skill>/scripts/lua/probes/textcover.lua --var RANGES=..`
count too when they sit under work/qa/cover. Waivers (debug/unused text, D9): docs/text_unshown.tsv.
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from skill import SKILL  # noqa: E402
import script_index  # noqa: E402
import textdb  # noqa: E402

OUT = ROOT / "work" / "qa" / "cover"
STRINGS = ROOT / "build" / "strings.tsv"
ROM = ROOT / "build" / "onmyou_zeroshiki_en.gba"
WAIVE = ROOT / "docs" / "text_unshown.tsv"
HOLD = 4000  # frames after the script's first text op: mash A (every 40 frames) pages through its dialogue


def ranges(gap=0x1000):
    """Clusters of built text addresses, as the probe's RANGES string (GBA bus addresses)."""
    addrs = sorted(int(l.split("\t")[1], 16) for l in STRINGS.read_text(encoding="utf-8").splitlines() if l)
    out, lo, hi = [], addrs[0], addrs[0]
    for a in addrs[1:]:
        if a - hi > gap:
            out.append((lo, hi))
            lo = a
        hi = a
    out.append((lo, hi))
    return ",".join(f"{lo:X}-{hi + 1:X}" for lo, hi in out)


def script_scenes():
    """(scene name, script id) for every StartScript id whose script holds a text run."""
    orig = script_index.ROM.read_bytes()
    texts = {int(e["id"], 16) for es in textdb.load().values() for e in es if "op" in e}
    starts = sorted(texts)
    out = []
    for sid, off, _, _ in script_index.scripts(orig):
        end = orig.index(b"\0", off)
        if any(off <= t < end for t in starts):
            out.append((f"cov_{sid}", sid))
    return out


def write_scenes():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [f"{n} script {sid} hold={HOLD} frames={20000 + HOLD}" for n, sid in script_scenes()]
    path = OUT / "scenes.txt"
    path.write_text("# generated by tools/debug/cover.py scenes\n" + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"{len(rows)} scenes -> {path.relative_to(ROOT)}")
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["scenes", "ranges", "run", "report"])
    ap.add_argument("--only")
    ap.add_argument("--jobs", default="4")
    a = ap.parse_args()
    if a.cmd == "scenes":
        write_scenes()
    elif a.cmd == "ranges":
        print(ranges())
    elif a.cmd == "run":
        scenes = write_scenes()
        cmd = [sys.executable, "-X", "utf8", str(ROOT / "tools" / "debug" / "warp_all.py"), str(ROM),
               "--scenes", str(scenes), "--out", str(OUT / "run"), "--states", str(OUT / "states"),
               "--jobs", a.jobs, "--probe", str(Path(SKILL) / "scripts" / "lua" / "probes" / "textcover.lua"),
               "--var", f"RANGES='{ranges()}'"]
        if a.only:
            cmd += ["--only", a.only]
        sys.exit(subprocess.run(cmd).returncode)
    else:
        cmd = [sys.executable, "-X", "utf8", str(Path(SKILL) / "scripts" / "textcover.py"), str(OUT), str(STRINGS)]
        if WAIVE.exists():
            cmd += ["--waive", str(WAIVE)]
        sys.exit(subprocess.run(cmd).returncode)


if __name__ == "__main__":
    main()
