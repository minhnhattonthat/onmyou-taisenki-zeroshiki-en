"""Text coverage for script branches: jump straight to the label before each script line the report never saw.

    python -X utf8 tools/debug/cover.py report      # first: work/qa/cover/report.txt
    python -X utf8 tools/debug/labeljobs.py [--jobs 8] [--list]

Most unseen script text sits after a `/124 N` label that the script reaches only under some story flag (NPC talk
changes per chapter: `/123 0000 FLAG 0001 9999 N`). `/123 0004 0000 0000 SCRIPT LABEL` jumps there unconditionally
(kind 4 = always; script id and label are decimal digits), so each scene is a `raw` warp running that one jump, with
A mashed to page through the dialogue. Scenes are one per (script, nearest label before an unseen line). Lines with no
label before them are listed, not run. Out: work/qa/cover/labels/<scene>/log.txt (counted by `cover.py report`).
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "debug"))
from skill import SKILL  # noqa: E402
import cover  # noqa: E402
import script_index  # noqa: E402

OUT = ROOT / "work" / "qa" / "cover" / "labels"
LABEL = re.compile(rb"/124(\d{4})")


def unseen():
    rep = cover.OUT / "report.txt"
    return {int(l.split()[2], 16) for l in rep.read_text(encoding="utf-8").splitlines() if l.startswith("NEVER SHOWN")}


def plan():
    miss = unseen()
    runs = set()
    for f in sorted((ROOT / "script").glob("*.json")):
        for e in json.loads(f.read_text(encoding="utf-8"))["entries"]:
            if "op" in e and int(e["id"], 16) in miss:
                runs.add(int(e["id"], 16))
    orig = script_index.ROM.read_bytes()
    scenes, nolabel = {}, []
    for sid, off, _, _ in script_index.scripts(orig):
        end = orig.index(b"\0", off)
        inside = sorted(t for t in runs if off <= t < end)
        if not inside:
            continue
        labels = [(m.start(), int(m.group(1))) for m in LABEL.finditer(orig, off, end)]
        for t in inside:
            before = [n for pos, n in labels if pos < t]
            if before:
                scenes.setdefault((sid, before[-1]), []).append(t)
            else:
                nolabel.append((sid, t))
    return scenes, nolabel


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", default="8")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    scenes, nolabel = plan()
    print(f"{len(scenes)} label scenes for {sum(len(v) for v in scenes.values())} lines; "
          f"{len(nolabel)} lines with no label before them")
    if a.list:
        for (sid, n), ts in sorted(scenes.items()):
            print(f"lab_{sid}_{n}", " ".join(f"{t:X}" for t in ts))
        for sid, t in nolabel:
            print("nolabel", sid, f"{t:X}")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [f"lab_{sid}_{n} raw /123000400000000{sid:04d}{n:04d} hold=2400"
            for (sid, n) in sorted(scenes)]
    path = OUT / "scenes.txt"
    path.write_text("# generated by tools/debug/labeljobs.py\n" + "\n".join(rows) + "\n", encoding="utf-8")
    cmd = [sys.executable, "-X", "utf8", str(ROOT / "tools" / "debug" / "warp_all.py"), str(cover.ROM),
           "--scenes", str(path), "--out", str(OUT), "--states", str(OUT / "states"), "--jobs", a.jobs,
           "--probe", str(Path(SKILL) / "scripts" / "lua" / "probes" / "textcover.lua"),
           "--var", f"RANGES='{cover.ranges()}'"]
    sys.exit(subprocess.run(cmd).returncode)


if __name__ == "__main__":
    main()
