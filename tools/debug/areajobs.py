"""Text coverage for the area names: reopen the map menu over and over while areacycle.lua feeds it each name.

    python -X utf8 tools/debug/areajobs.py [--jobs 8]

The map menu shows only the current area's name, drawn once per opening (0x080163F6). Each job opens it, then
closes (B, B) and reopens it (START, A) once per name, while tools/debug/areacycle.lua substitutes the next distinct
pointer of its slice of the 224-word area table 0x0840B334. Out: work/qa/cover/areas/area_NN/log.txt (counted by
`tools/debug/cover.py report`; the run passes when every job logged AC_DONE).
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "debug"))
from skill import SKILL  # noqa: E402
import cover  # noqa: E402

OUT = ROOT / "work" / "qa" / "cover" / "areas"
WORDS = 224


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", type=int, default=8)
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    size = -(-WORDS // a.jobs)
    rows = []
    for j in range(a.jobs):
        lo, hi = j * size, min(WORDS, (j + 1) * size)
        press = "6:start|300:-|6:left|30:-|6:a|200:-" + "|6:b|150:-|6:b|150:-|6:start|300:-|6:a|200:-" * (hi - lo)
        rows.append(f"area_{j:02d} field 23  flags=0,1,2,21,22,23,24,28 press={press} mash=0 hold=1 "
                    f"frames={4000 + 820 * (hi - lo)}")
    scenes = OUT / "scenes.txt"
    scenes.write_text("# generated by tools/debug/areajobs.py\n" + "\n".join(rows) + "\n", encoding="utf-8")
    procs = []
    for j in range(a.jobs):
        lo, hi = j * size, min(WORDS, (j + 1) * size)
        cmd = [sys.executable, "-X", "utf8", str(ROOT / "tools" / "debug" / "warp_all.py"), str(cover.ROM),
               "--scenes", str(scenes), "--only", f"area_{j:02d}", "--out", str(OUT), "--states", str(OUT / "states"),
               "--probe", str(ROOT / "tools" / "debug" / "areacycle.lua"),
               "--probe", str(Path(SKILL) / "scripts" / "lua" / "probes" / "textcover.lua"),
               "--var", f"RANGES='{cover.ranges()}'", "--var", f"START={lo}", "--var", f"END={hi}"]
        procs.append(subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))
    for p in procs:
        p.wait()
    bad = 0
    for j in range(a.jobs):
        log = OUT / f"area_{j:02d}" / "log.txt"
        text = log.read_text(encoding="utf-8", errors="replace") if log.exists() else ""
        ok = "AC_DONE" in text
        bad += not ok
        print(f"area_{j:02d} {'ok ' if ok else 'BAD'} names={text.count(chr(10) + 'AC ') + text.startswith('AC ')}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
