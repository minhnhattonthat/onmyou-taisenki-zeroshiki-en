"""Text coverage for the shikigami status pages: one scene per shikigami id, each visiting all four pages.

    python -X utf8 tools/debug/shikijobs.py [--ids 0-75] [--jobs 6]

The status page shows the party shikigami whose id is the u8 at 0x020025B8 (Kogenta = 15; ids 0x48..0x4B are
special-cased by the name routine 0x08035BF0). Each scene pokes that id before opening the menu, then presses LEFT
through pages 4, 3, 2, 1 (page u16 0x0200512C) with a shot every 150 frames, under the skill's textcover.lua probe.
Out: work/qa/cover/shiki/<scene>/ (log.txt counted by `tools/debug/cover.py report`, seq_*.png + sheet.png).
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "debug"))
from skill import SKILL  # noqa: E402
import cover  # noqa: E402

OUT = ROOT / "work" / "qa" / "cover" / "shiki"
PRESS = "6:start|300:-|6:right|30:-|6:right|30:-|6:a|300:-|6:left|150:-|6:left|150:-|6:left|150:-|6:left|300:-"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ids", default="0-75")
    ap.add_argument("--jobs", default="6")
    ap.add_argument("--unlock", action="store_true",
                    help="also set every bit of the two per-shikigami unlock arrays 0x02002DC2 / 0x02002DCC (10 bytes "
                         "each, read by 0x080026A0 / 0x0800270C: the page then shows the second technique name, "
                         "str_techniques_b); out work/qa/cover/shiki_unlock/")
    a = ap.parse_args()
    lo, hi = (int(x) for x in a.ids.split("-"))
    out = OUT.with_name("shiki_unlock") if a.unlock else OUT
    extra = "".join(f",0x{0x02002DC2 + 2 * k:08X}:65535" for k in range(10)) if a.unlock else ""
    out.mkdir(parents=True, exist_ok=True)
    rows = [f"shiki_{i:02d} field 23  flags=0,1,2,21,22,23,24,28 press={PRESS} poke=0x020025B8:{i}{extra} "
            f"mash=0 hold=1" for i in range(lo, hi + 1)]
    scenes = out / "scenes.txt"
    scenes.write_text("# generated by tools/debug/shikijobs.py\n" + "\n".join(rows) + "\n", encoding="utf-8")
    cmd = [sys.executable, "-X", "utf8", str(ROOT / "tools" / "debug" / "warp_all.py"), str(cover.ROM),
           "--scenes", str(scenes), "--out", str(out), "--states", str(out / "states"), "--jobs", a.jobs,
           "--seq", "150", "--hold", "1500",
           "--probe", str(Path(SKILL) / "scripts" / "lua" / "probes" / "textcover.lua"),
           "--var", f"RANGES='{cover.ranges()}'"]
    sys.exit(subprocess.run(cmd).returncode)


if __name__ == "__main__":
    main()
